package cn.edu.nun.campus.knowledge;

import cn.edu.nun.campus.auth.JwtAuthFilter;
import cn.edu.nun.campus.auth.JwtService;
import cn.edu.nun.campus.common.BizException;
import cn.edu.nun.campus.common.GlobalExceptionHandler;
import cn.edu.nun.campus.config.SecurityConfig;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.autoconfigure.orm.jpa.HibernateJpaAutoConfiguration;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;

import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest(classes = KnowledgeImportTest.TestApplication.class, properties = {
        "spring.config.location=optional:classpath:/knowledge-import-test-only.properties",
        "spring.config.import=",
        "spring.autoconfigure.exclude=org.springframework.boot.autoconfigure.security.servlet.UserDetailsServiceAutoConfiguration,org.springframework.boot.autoconfigure.data.jpa.JpaRepositoriesAutoConfiguration",
        "spring.datasource.url=jdbc:h2:mem:knowledgeimport;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
        "spring.datasource.username=sa", "spring.datasource.password=", "spring.flyway.enabled=false",
        "app.jwt.secret=knowledge-import-test-only-key-01234567890123456789",
        "app.jwt.expire-minutes=120"
})
@AutoConfigureMockMvc
class KnowledgeImportTest {
    @Configuration(proxyBeanMethods = false)
    @EnableAutoConfiguration(exclude = HibernateJpaAutoConfiguration.class)
    @Import({KnowledgeImportService.class, KnowledgeImportController.class, JwtService.class,
            JwtAuthFilter.class, SecurityConfig.class, GlobalExceptionHandler.class})
    static class TestApplication {}

    @Autowired MockMvc mvc;
    @Autowired ObjectMapper json;
    @Autowired JwtService jwt;
    @Autowired JdbcTemplate jdbc;
    @Autowired KnowledgeImportService imports;

    @BeforeEach void createIsolatedTable() {
        jdbc.execute("DROP TABLE IF EXISTS knowledge_item");
        jdbc.execute("""
                CREATE TABLE knowledge_item (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    import_key VARCHAR(160) UNIQUE, type VARCHAR(20) NOT NULL,
                    title VARCHAR(255) NOT NULL CHECK (title <> 'DB_REJECT_TEST'),
                    content TEXT NOT NULL, summary VARCHAR(500), source_name VARCHAR(255),
                    source_url VARCHAR(1024), official BOOLEAN NOT NULL,
                    department VARCHAR(128), source_site VARCHAR(64), source_category VARCHAR(255),
                    published_at TIMESTAMP WITH TIME ZONE, imported_at TIMESTAMP WITH TIME ZONE,
                    status VARCHAR(20) NOT NULL, version INT NOT NULL,
                    created_by BIGINT, reviewed_by BIGINT,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
                )
                """);
    }

    private String auth(String role) { return "Bearer " + jwt.issue(17L, "test", role); }

    private Map<String, Object> article(String key) {
        Map<String, Object> result = new LinkedHashMap<>();
        result.put("externalKey", key.repeat(64)); result.put("type", "NOTICE");
        result.put("title", "学校测试通知"); result.put("content", "测试正文，不代表真实学校通知。");
        result.put("summary", "测试摘要"); result.put("sourceName", "北方民族大学官网");
        result.put("sourceUrl", "https://www.nmu.edu.cn/info/1034/123.htm");
        result.put("official", true); result.put("department", "测试部门");
        result.put("sourceSite", "www"); result.put("sourceCategory", "通知公告");
        result.put("publishedAt", "2020-03-04T00:00:00+08:00");
        return result;
    }

    private Map<String, Object> batch(List<Map<String, Object>> items) {
        return Map.of("dataset", "nmu-official", "items", items);
    }

    private JsonNode save(List<Map<String, Object>> items) throws Exception {
        String response = mvc.perform(post("/api/v1/admin/knowledge/import")
                        .header("Authorization", auth("ADMIN")).contentType("application/json")
                        .content(json.writeValueAsString(batch(items))))
                .andExpect(status().isOk()).andExpect(jsonPath("$.code").value(0))
                .andReturn().getResponse().getContentAsString();
        return json.readTree(response).get("data");
    }

    private long count() { return jdbc.queryForObject("SELECT count(*) FROM knowledge_item", Long.class); }

    @Test void importRequiresAnAdministratorRatherThanMerelyAModerator() throws Exception {
        String body = json.writeValueAsString(batch(List.of(article("a"))));
        mvc.perform(post("/api/v1/admin/knowledge/import").contentType("application/json").content(body))
                .andExpect(status().isUnauthorized());
        for (String role : List.of("GUEST", "STUDENT", "MODERATOR")) {
            mvc.perform(post("/api/v1/admin/knowledge/import").header("Authorization", auth(role))
                            .contentType("application/json").content(body))
                    .andExpect(status().isForbidden());
        }
        assertEquals(0, count());
        assertEquals(1, save(List.of(article("a"))).get("created").asInt());
    }

    @Test void preservesSourceDateAndProvenanceAndPublishesTheImportedArticle() throws Exception {
        JsonNode saved = save(List.of(article("a")));
        assertEquals(1, saved.get("created").asInt()); assertEquals(0, saved.get("skipped").asInt());
        long id = saved.get("ids").get(0).asLong();
        Map<String, Object> row = jdbc.queryForMap("SELECT * FROM knowledge_item WHERE id = ?", id);
        assertEquals("PUBLISHED", row.get("STATUS")); assertEquals("www", row.get("SOURCE_SITE"));
        assertEquals("通知公告", row.get("SOURCE_CATEGORY"));
        assertEquals("nmu-official:" + "a".repeat(64), row.get("IMPORT_KEY"));
        assertEquals(17L, row.get("CREATED_BY")); assertEquals(17L, row.get("REVIEWED_BY"));
        assertEquals(OffsetDateTime.parse("2020-03-04T00:00:00+08:00").toInstant(),
                ((OffsetDateTime) row.get("PUBLISHED_AT")).toInstant());
        assertNotNull(row.get("IMPORTED_AT"));
    }

    @Test void aRepeatedImportDoesNotReplaceManualEditsOrRepublishExpiredEntries() throws Exception {
        long id = save(List.of(article("a"))).get("ids").get(0).asLong();
        jdbc.update("UPDATE knowledge_item SET title = ?, content = ?, status = 'EXPIRED', version = 2 WHERE id = ?",
                "管理员已修订", "保留人工修订正文", id);
        Map<String, Object> changed = article("a"); changed.put("content", "再次抓取产生的新正文");
        JsonNode repeated = save(List.of(changed));
        assertEquals(0, repeated.get("created").asInt()); assertEquals(1, repeated.get("skipped").asInt());
        assertEquals(id, repeated.get("ids").get(0).asLong()); assertEquals(1, count());
        Map<String, Object> row = jdbc.queryForMap("SELECT * FROM knowledge_item WHERE id = ?", id);
        assertEquals("管理员已修订", row.get("TITLE")); assertEquals("保留人工修订正文", row.get("CONTENT"));
        assertEquals("EXPIRED", row.get("STATUS")); assertEquals(2, row.get("VERSION"));
    }

    @Test void missingSourceDatesRemainUnknownAndDuplicatesWithinABatchAreSkipped() throws Exception {
        Map<String, Object> item = article("a"); item.put("publishedAt", null);
        JsonNode saved = save(List.of(item, item));
        assertEquals(1, saved.get("created").asInt()); assertEquals(1, saved.get("skipped").asInt());
        assertEquals(saved.get("ids").get(0), saved.get("ids").get(1));
        assertNull(jdbc.queryForMap("SELECT published_at FROM knowledge_item").get("PUBLISHED_AT"));
    }

    @Test void rejectsAnInvalidArticleAnywhereInTheBatchBeforeWriting() throws Exception {
        for (String invalid : List.of("https://nmu.edu.cn.evil.test/a", "https://other.example/a",
                "file:///school.txt", "https://user@www.nmu.edu.cn/info", "javascript:alert(1)", "not a url")) {
            Map<String, Object> bad = article("b"); bad.put("sourceUrl", invalid);
            mvc.perform(post("/api/v1/admin/knowledge/import").header("Authorization", auth("ADMIN"))
                            .contentType("application/json")
                            .content(json.writeValueAsString(batch(List.of(article("a"), bad)))))
                    .andExpect(jsonPath("$.code").value(400));
            assertEquals(0, count());
        }
    }

    @Test void acceptsDepartmentSubdomainsAndTheRootDomain() throws Exception {
        Map<String, Object> subdomain = article("a");
        subdomain.put("sourceUrl", "http://jwc.nmu.edu.cn/info/123.htm");
        Map<String, Object> root = article("b"); root.put("sourceUrl", "https://nmu.edu.cn/");
        assertEquals(2, save(List.of(subdomain, root)).get("created").asInt());
    }

    @Test void rejectsOversizedOrMalformedBatchesWithNoWrites() throws Exception {
        List<Map<String, Object>> tooMany = new ArrayList<>();
        for (int i = 0; i < 101; i++) tooMany.add(article("a"));
        for (List<Map<String, Object>> items : List.of(List.<Map<String, Object>>of(), tooMany)) {
            mvc.perform(post("/api/v1/admin/knowledge/import").header("Authorization", auth("ADMIN"))
                            .contentType("application/json").content(json.writeValueAsString(batch(items))))
                    .andExpect(status().isBadRequest());
        }
        for (Map<String, Object> change : List.<Map<String, Object>>of(
                Map.of("externalKey", "bad-key"), Map.of("content", "长".repeat(300001)),
                Map.of("title", "长".repeat(256)), Map.of("official", false))) {
            Map<String, Object> bad = article("a"); bad.putAll(change);
            mvc.perform(post("/api/v1/admin/knowledge/import").header("Authorization", auth("ADMIN"))
                            .contentType("application/json").content(json.writeValueAsString(batch(List.of(bad)))))
                    .andExpect(status().isBadRequest());
        }
        assertEquals(0, count());
    }

    @Test void aDatabaseFailureRollsBackEarlierInsertsInThatBatch() throws Exception {
        Map<String, Object> bad = article("b"); bad.put("title", "DB_REJECT_TEST");
        KnowledgeImportService.Batch request = json.convertValue(batch(List.of(article("a"), bad)),
                KnowledgeImportService.Batch.class);
        BizException failure = assertThrows(BizException.class, () -> imports.importBatch(request, 17L));
        assertEquals(500, failure.getCode()); assertFalse(failure.getMessage().contains("测试正文"));
        assertNull(failure.getCause()); assertEquals(0, count());
    }
}
